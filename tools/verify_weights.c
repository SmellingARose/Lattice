int main(void)
{
    int errors = 0;

    /* === 1. Verify restriction 1D weights sum to 1 === */
    double rsum = 0.0;
    for (int i = 0; i < RESTRICT_STENCIL; i++) rsum += restrict_w[i];
    printf("Restriction 1D sum: %.17e (error: %.2e)\n", rsum, fabs(rsum - 1.0));
    if (fabs(rsum - 1.0) > 1e-14) { printf("  FAIL\n"); errors++; }

    /* === 2. Verify restriction 1D symmetry === */
    for (int i = 0; i < RESTRICT_STENCIL / 2; i++) {
        if (restrict_w[i] != restrict_w[RESTRICT_STENCIL - 1 - i]) {
            printf("  FAIL: restrict_w[%d] != restrict_w[%d]\n", i, RESTRICT_STENCIL-1-i);
            errors++;
        }
    }
    printf("Restriction symmetry: OK\n");

    /* === 3. Verify restrict_wkj bit-exactness === */
    int wkj_ok = 1;
    for (int sk = 0; sk < RESTRICT_STENCIL; sk++) {
        for (int sj = 0; sj < RESTRICT_STENCIL; sj++) {
            double expected = restrict_w[sk] * restrict_w[sj];
            double got = restrict_wkj[sk][sj];
            /* Bit-exact comparison via memcmp */
            if (memcmp(&expected, &got, sizeof(double)) != 0) {
                printf("  FAIL: restrict_wkj[%d][%d] = %.17e, expected %.17e\n",
                       sk, sj, got, expected);
                wkj_ok = 0;
                errors++;
            }
        }
    }
    printf("Restriction wkj table: %s (36 entries)\n", wkj_ok ? "BIT-EXACT" : "MISMATCH");

    /* === 4. Verify 3D restriction weights sum to 1 === */
    double rsum3d = 0.0;
    for (int sk = 0; sk < RESTRICT_STENCIL; sk++)
        for (int sj = 0; sj < RESTRICT_STENCIL; sj++)
            for (int si = 0; si < RESTRICT_STENCIL; si++)
                rsum3d += restrict_w[sk] * restrict_w[sj] * restrict_w[si];
    printf("Restriction 3D sum: %.17e (error: %.2e)\n", rsum3d, fabs(rsum3d - 1.0));
    if (fabs(rsum3d - 1.0) > 1e-13) { printf("  FAIL\n"); errors++; }

    /* === 5. Verify prolongation 1D weights sum to 1 === */
    double psum = 0.0;
    for (int i = 0; i < PROLONG_STENCIL; i++) psum += prolong_w[i];
    printf("Prolongation 1D sum: %.17e (error: %.2e)\n", psum, fabs(psum - 1.0));
    if (fabs(psum - 1.0) > 1e-14) { printf("  FAIL\n"); errors++; }

    /* === 6. Verify prolongation reversed 1D weights also sum to 1 === */
    double psum_rev = 0.0;
    for (int i = 0; i < PROLONG_STENCIL; i++) psum_rev += prolong_w[PROLONG_STENCIL-1-i];
    printf("Prolongation reversed 1D sum: %.17e (error: %.2e)\n", psum_rev, fabs(psum_rev - 1.0));
    if (fabs(psum_rev - 1.0) > 1e-14) { printf("  FAIL\n"); errors++; }

    /* === 7. Verify prolongation wkj table bit-exactness === */
    printf("\nProlongation wkj verification (4 octant combos × 7×7 = 196 entries):\n");
    int pwkj_ok = 1;
    for (int ok = 0; ok < 2; ok++) {
        for (int oj = 0; oj < 2; oj++) {
            int combo = ok * 2 + oj;
            int combo_ok = 1;
            for (int sk = 0; sk < PROLONG_STENCIL; sk++) {
                int wk = ok ? (PROLONG_STENCIL - 1 - sk) : sk;
                for (int sj = 0; sj < PROLONG_STENCIL; sj++) {
                    int wj = oj ? (PROLONG_STENCIL - 1 - sj) : sj;
                    double expected = prolong_w[wk] * prolong_w[wj];
                    double got = prolong_wkj[combo][sk][sj];
                    if (memcmp(&expected, &got, sizeof(double)) != 0) {
                        printf("  FAIL: prolong_wkj[%d][%d][%d] = %.17e, expected %.17e\n",
                               combo, sk, sj, got, expected);
                        combo_ok = 0;
                        pwkj_ok = 0;
                        errors++;
                    }
                }
            }
            /* Verify 2D sum for this combo */
            double sum2d = 0.0;
            for (int sk = 0; sk < PROLONG_STENCIL; sk++)
                for (int sj = 0; sj < PROLONG_STENCIL; sj++)
                    sum2d += prolong_wkj[combo][sk][sj];
            printf("  combo(%d,%d): %s, 2D sum error: %.2e\n",
                   ok, oj, combo_ok ? "BIT-EXACT" : "MISMATCH", fabs(sum2d - 1.0));
            if (fabs(sum2d - 1.0) > 1e-14) { printf("    FAIL\n"); errors++; }
        }
    }
    printf("Prolongation wkj table: %s (196 entries)\n", pwkj_ok ? "BIT-EXACT" : "MISMATCH");

    /* === 8. Verify that the original fraction expressions are correct === */
    printf("\nFraction verification:\n");

    /* Restriction: w should sum to 1 using exact fractions */
    /* -17/11520 + 97/3840 + 2743/5760 + 2743/5760 + 97/3840 + -17/11520 */
    /* LCD = 11520 */
    /* -17 + 3*97 + 2*2743 + 2*2743 + 3*97 + (-17) */
    /* = -17 + 291 + 5486 + 5486 + 291 + (-17) = 11520 → 11520/11520 = 1 ✓ */
    long num = -17 + 3*97 + 2*2743 + 2*2743 + 3*97 + (-17);
    printf("  Restriction LCD=11520: sum of numerators = %ld (expected 11520)\n", num);
    if (num != 11520) { printf("    FAIL\n"); errors++; }

    /* Prolongation: w should sum to 1 using exact fractions */
    /* LCD = 65536 */
    /* 273 + 2*(-1287) + 15015 + 4*15015 + (-9009) + 2*1001 + (-231) */
    /* = 273 - 2574 + 15015 + 60060 - 9009 + 2002 - 231 = 65536 */
    long pnum = 273 + (-2)*1287 + 15015 + 4*15015 + (-9009) + 2*1001 + (-231);
    printf("  Prolongation LCD=65536: sum of numerators = %ld (expected 65536)\n", pnum);
    if (pnum != 65536) { printf("    FAIL\n"); errors++; }

    printf("\n=== %s (%d errors) ===\n", errors ? "FAIL" : "ALL PASSED", errors);
    return errors;
}
